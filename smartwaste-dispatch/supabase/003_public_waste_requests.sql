-- Public waste collection requests (Medium waste booking; legacy Large service types retained for existing records)
-- Run this additive migration in Supabase SQL Editor after reviewing it.
-- It creates one new table and does not modify or delete existing project data.

create table if not exists public.waste_requests (
  id bigint generated by default as identity primary key,
  requester_id uuid not null references auth.users(id) on delete cascade,
  waste_size text not null check (waste_size in ('medium', 'large')),
  service_type text not null check (
    service_type in ('Medium waste collection', 'Large-waste driver', 'Large-waste pickup')
  ),
  pickup_address text not null check (length(trim(pickup_address)) between 5 and 500),
  notes text,
  latitude double precision,
  longitude double precision,
  gps_accuracy_m double precision,
  maps_url text,
  status text not null default 'pending'
    check (status in ('pending', 'approved', 'scheduled', 'completed', 'rejected')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint waste_requests_latitude_range check (latitude is null or latitude between -90 and 90),
  constraint waste_requests_longitude_range check (longitude is null or longitude between -180 and 180)
);

-- Safe additive upgrades for projects that already ran an earlier version.
alter table public.waste_requests add column if not exists gps_accuracy_m double precision;
alter table public.waste_requests add column if not exists maps_url text;

create index if not exists waste_requests_requester_created_idx
  on public.waste_requests (requester_id, created_at desc);

create index if not exists waste_requests_status_created_idx
  on public.waste_requests (status, created_at desc);

alter table public.waste_requests enable row level security;

drop policy if exists "Users create own waste requests" on public.waste_requests;
create policy "Users create own waste requests"
  on public.waste_requests for insert to authenticated
  with check (requester_id = (select auth.uid()));

drop policy if exists "Users view own waste requests" on public.waste_requests;
create policy "Users view own waste requests"
  on public.waste_requests for select to authenticated
  using (
    requester_id = (select auth.uid())
    or exists (
      select 1 from public.profiles p
      where p.id = (select auth.uid()) and p.role = 'supervisor'
    )
  );

drop policy if exists "Supervisors update waste requests" on public.waste_requests;
create policy "Supervisors update waste requests"
  on public.waste_requests for update to authenticated
  using (
    exists (
      select 1 from public.profiles p
      where p.id = (select auth.uid()) and p.role = 'supervisor'
    )
  )
  with check (
    exists (
      select 1 from public.profiles p
      where p.id = (select auth.uid()) and p.role = 'supervisor'
    )
  );

grant select, insert on public.waste_requests to authenticated;
grant update (status, updated_at) on public.waste_requests to authenticated;
grant usage, select on sequence public.waste_requests_id_seq to authenticated;
