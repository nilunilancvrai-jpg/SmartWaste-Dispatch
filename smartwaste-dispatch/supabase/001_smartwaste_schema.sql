-- No direct client INSERT/UPDATE/DELETE policies are intentionally provided.
-- Mutations go through SECURITY DEFINER RPCs that validate role and ownership.

create or replace function public.invite_worker(p_email text, p_full_name text default null)
returns jsonb language plpgsql security definer set search_path = public, auth
as $$
declare target_user auth.users%rowtype;
begin
  if auth.uid() is null or public.current_app_role() <> 'supervisor' then
    raise exception 'Supervisor access required';
  end if;
  if p_email is null or position('@' in p_email)=0 then raise exception 'Enter a valid email address'; end if;
  insert into public.staff_invites(email,role,invited_by)
  values(lower(trim(p_email)),'worker',auth.uid())
  on conflict(email) do update set role='worker', invited_by=auth.uid(), created_at=now();
  select * into target_user from auth.users where lower(email)=lower(trim(p_email));
  if target_user.id is not null then
    if exists (select 1 from public.profiles where id=target_user.id and role='supervisor') then
      raise exception 'A supervisor account cannot be converted to a worker';
    end if;
    update public.profiles set role='worker', full_name=coalesce(nullif(trim(p_full_name),''),full_name), updated_at=now()
    where id=target_user.id;
    delete from public.staff_invites where email=lower(trim(p_email));
  end if;
  return jsonb_build_object('success',true,'registered',(target_user.id is not null),'email',lower(trim(p_email)));
end;
$$;

create or replace function public.assign_collection_task(p_bin_id bigint, p_worker_id uuid)
returns public.assignments language plpgsql security definer set search_path = public
as $$
declare b public.bins%rowtype; w public.profiles%rowtype; a public.assignments%rowtype;
begin
  if auth.uid() is null or public.current_app_role()<>'supervisor' then raise exception 'Supervisor access required'; end if;
  select * into b from public.bins where id=p_bin_id for update;
  if b.id is null then raise exception 'Bin not found'; end if;
  if b.status<>'available' or b.fill<80 then raise exception 'This bin does not require collection'; end if;
  select * into w from public.profiles where id=p_worker_id and role='worker';
  if w.id is null then raise exception 'Select an authorized worker'; end if;
  insert into public.assignments(bin_id,worker_id,assigned_by,status)
  values(p_bin_id,p_worker_id,auth.uid(),'assigned') returning * into a;
  return a;
exception when unique_violation then raise exception 'This bin already has an active assignment';
end;
$$;

create or replace function public.set_worker_task_status(p_task_id uuid, p_status text)
returns public.assignments language plpgsql security definer set search_path = public
as $$
declare a public.assignments%rowtype;
begin
  if auth.uid() is null or public.current_app_role()<>'worker' then raise exception 'Worker access required'; end if;
  if p_status not in ('on-the-way','collecting') then raise exception 'Invalid worker task status'; end if;
  update public.assignments set status=p_status, updated_at=now()
  where id=p_task_id and worker_id=auth.uid() and status in ('assigned','on-the-way','collecting')
  returning * into a;
  if a.id is null then raise exception 'Task not found or not assigned to you'; end if;
  return a;
end;
$$;

create or replace function public.complete_collection(
  p_task_id uuid, p_worker_lat double precision, p_worker_lng double precision, p_gps_accuracy_m double precision
)
returns jsonb language plpgsql security definer set search_path = public
as $$
declare a public.assignments%rowtype; b public.bins%rowtype;
begin
  if auth.uid() is null or public.current_app_role()<>'worker' then raise exception 'Worker access required'; end if;
  if p_gps_accuracy_m is null or p_gps_accuracy_m>10 then raise exception 'GPS accuracy must be 10 metres or better'; end if;
  if p_worker_lat is null or p_worker_lng is null or p_worker_lat not between -90 and 90 or p_worker_lng not between -180 and 180 then raise exception 'Valid GPS coordinates are required'; end if;
  select * into a from public.assignments where id=p_task_id and worker_id=auth.uid() and status not in ('collected','cancelled') for update;
  if a.id is null then raise exception 'Active task not found for this worker'; end if;
  select * into b from public.bins where id=a.bin_id for update;
  if b.status<>'available' or b.fill<80 then raise exception 'Bin is no longer eligible for collection'; end if;
  insert into public.collection_history(bin_id,bin_name,worker_id,previous_fill,worker_lat,worker_lng,gps_accuracy_m)
  values(b.id,b.name,auth.uid(),b.fill,p_worker_lat,p_worker_lng,p_gps_accuracy_m);
  update public.bins set fill=0, updated_at=now() where id=b.id;
  update public.assignments set status='collected',updated_at=now(),completed_at=now() where id=a.id;
  return jsonb_build_object('success',true,'bin_id',b.id,'previous_fill',b.fill);
end;
$$;

create or replace function public.supervisor_set_bin_status(p_bin_id bigint, p_status text)
returns public.bins language plpgsql security definer set search_path = public
as $$
declare b public.bins%rowtype;
begin
  if auth.uid() is null or public.current_app_role()<>'supervisor' then raise exception 'Supervisor access required'; end if;
  if p_status not in ('available','out-of-service') then raise exception 'Invalid bin status'; end if;
  update public.bins set status=p_status,updated_at=now() where id=p_bin_id returning * into b;
  if b.id is null then raise exception 'Bin not found'; end if;
  if p_status='out-of-service' then
    update public.assignments set status='cancelled',updated_at=now()
    where bin_id=p_bin_id and status not in ('collected','cancelled');
  end if;
  return b;
end;
$$;

