create extension if not exists pgcrypto;

create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  email text not null unique,
  full_name text,
  role text not null default 'public' check (role in ('public','worker','supervisor')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.staff_invites (
  email text primary key,
  role text not null check (role in ('worker','supervisor')),
  invited_by uuid references public.profiles(id),
  created_at timestamptz not null default now()
);

create table if not exists public.bins (
  id bigint generated by default as identity primary key,
  name text not null,
  address text not null,
  lat double precision not null check (lat between -90 and 90),
  lng double precision not null check (lng between -180 and 180),
  fill integer not null default 0 check (fill between 0 and 100),
  status text not null default 'available' check (status in ('available','out-of-service')),
  updated_at timestamptz not null default now()
);

create table if not exists public.assignments (
  id uuid primary key default gen_random_uuid(),
  bin_id bigint not null references public.bins(id),
  worker_id uuid not null references public.profiles(id),
  assigned_by uuid not null references public.profiles(id),
  status text not null default 'assigned' check (status in ('assigned','on-the-way','collecting','collected','cancelled')),
  assigned_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  completed_at timestamptz
);

create unique index if not exists assignments_one_active_per_bin
  on public.assignments(bin_id)
  where status not in ('collected','cancelled');

create table if not exists public.collection_history (
  id uuid primary key default gen_random_uuid(),
  bin_id bigint not null references public.bins(id),
  bin_name text not null,
  worker_id uuid not null references public.profiles(id),
  previous_fill integer not null check (previous_fill between 80 and 100),
  completed_at timestamptz not null default now(),
  worker_lat double precision,
  worker_lng double precision,
  gps_accuracy_m double precision
);

-- Role lookup helper is SECURITY DEFINER to avoid profiles RLS recursion.
create or replace function public.current_app_role()
returns text language sql stable security definer set search_path = public
as $$ select role from public.profiles where id = auth.uid() $$;

create or replace function public.handle_new_auth_user()
returns trigger language plpgsql security definer set search_path = public, auth
as $$
declare assigned_role text := 'public';
begin
  select role into assigned_role from public.staff_invites where lower(email)=lower(new.email);
  if assigned_role is null then assigned_role := 'public'; end if;
  insert into public.profiles(id,email,full_name,role)
  values(new.id, lower(new.email), coalesce(new.raw_user_meta_data->>'full_name',''), assigned_role)
  on conflict (id) do update set email=excluded.email, full_name=excluded.full_name;
  delete from public.staff_invites where lower(email)=lower(new.email);
  return new;
end;
$$;

drop trigger if exists on_auth_user_created_smartwaste on auth.users;
create trigger on_auth_user_created_smartwaste
after insert on auth.users for each row execute procedure public.handle_new_auth_user();

